// Builds src/lib/ai/catalog.generated.ts from prisma/schema.prisma: every model with its
// fields (type, optional, list, relation target, calendar-date columns, doc comments) and
// every enum. The AI assistant's database tool validates queries against this catalog and
// describes the schema to the model from it. Re-run after changing the schema:
//
//   npx tsx scripts/generate-ai-catalog.ts

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

type Field = { name: string; type: string; optional: boolean; list: boolean; kind: "scalar" | "enum" | "relation"; date?: boolean; fk?: string; doc?: string };
type Model = { name: string; table: string; doc?: string; fields: Field[] };

const root = join(__dirname, "..");
const src = readFileSync(join(root, "prisma", "schema.prisma"), "utf8").replace(/\r\n/g, "\n");
const lines = src.split("\n");

const modelNames = new Set([...src.matchAll(/^model (\w+) \{/gm)].map((m) => m[1]));
const enums: Record<string, string[]> = {};
const models: Model[] = [];

let docBuf: string[] = [];
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const t = line.trim();
  if (t.startsWith("///")) { docBuf.push(t.slice(3).trim()); continue; }
  const em = /^enum (\w+) \{/.exec(t);
  if (em) {
    const values: string[] = [];
    for (i++; i < lines.length && lines[i].trim() !== "}"; i++) {
      const v = lines[i].trim();
      if (v && !v.startsWith("//") && !v.startsWith("@@")) values.push(v.split(/\s+/)[0]);
    }
    enums[em[1]] = values;
    docBuf = [];
    continue;
  }
  const mm = /^model (\w+) \{/.exec(t);
  if (mm) {
    const model: Model = { name: mm[1], table: mm[1], doc: docBuf.join(" ") || undefined, fields: [] };
    docBuf = [];
    let fieldDoc: string[] = [];
    for (i++; i < lines.length && lines[i].trim() !== "}"; i++) {
      const f = lines[i].trim();
      if (f.startsWith("///")) { fieldDoc.push(f.slice(3).trim()); continue; }
      if (!f || f.startsWith("//")) { fieldDoc = []; continue; }
      if (f.startsWith("@@")) {
        const map = /@@map\("([^"]+)"\)/.exec(f);
        if (map) model.table = map[1];
        continue;
      }
      const fm = /^(\w+)\s+(\w+)(\[\])?(\?)?(.*)$/.exec(f);
      if (!fm) continue;
      const [, name, type, list, opt, rest] = fm;
      const kind: Field["kind"] = modelNames.has(type) ? "relation" : /^[A-Z]/.test(type) && !["String", "Int", "BigInt", "Float", "Decimal", "Boolean", "DateTime", "Json", "Bytes"].includes(type) ? "enum" : "scalar";
      const field: Field = { name, type, optional: !!opt, list: !!list, kind };
      if (type === "DateTime" && /@db\.Date\b/.test(rest)) field.date = true;
      const fk = /@relation\([^)]*fields:\s*\[(\w+)\]/.exec(rest);
      if (fk && kind === "relation") field.fk = fk[1];
      const trailing = /\/\/\s*(.+)$/.exec(rest);
      const doc = [...fieldDoc, trailing?.[1] ?? ""].filter(Boolean).join(" ");
      if (doc) field.doc = doc.slice(0, 160);
      model.fields.push(field);
      fieldDoc = [];
    }
    models.push(model);
    continue;
  }
  if (t && !t.startsWith("//")) docBuf = [];
}

const out = `// GENERATED by scripts/generate-ai-catalog.ts from prisma/schema.prisma — do not edit by hand.

export type CatalogField = { name: string; type: string; optional: boolean; list: boolean; kind: "scalar" | "enum" | "relation"; date?: boolean; fk?: string; doc?: string };
export type CatalogModel = { name: string; table: string; doc?: string; fields: CatalogField[] };

export const CATALOG_MODELS: CatalogModel[] = ${JSON.stringify(models)};

export const CATALOG_ENUMS: Record<string, string[]> = ${JSON.stringify(enums)};
`;
writeFileSync(join(root, "src", "lib", "ai", "catalog.generated.ts"), out);
console.log(`AI catalog: ${models.length} models, ${Object.keys(enums).length} enums`);
